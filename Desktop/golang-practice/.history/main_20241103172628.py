import pandas as pd

# Загрузка файла
file_path = 'credit-0b9d6b53-06a7-4321-91bc-d3635df3642c.xlsx'
data = pd.read_excel(file_path, header=1)

# Переименовываем столбцы (замените их на актуальные для вашего файла)
data.columns = ['Дата_заявки', 'Источник', 'Программа', 'Дата_начала', 'Начальная_сумма', 
                'Ставка', 'Срок', 'Кредитный_лимит', 'Годовой_доход', 'Месячный_доход',
                'Образование', 'Возраст', 'Паспорт', 'Пол', 'Город', 'Университет', 
                'Семья', 'Тип_студента', 'Курс', 'Средний_балл', 'Срок_окончания']

# 1. Фильтруем данные для магистров и считаем количество заявок по университетам
masters_data = data[data['Тип_студента'].str.upper() == 'MASTER']
university_counts = masters_data['Университет'].value_counts()

# Проверка на наличие достаточного количества университетов
if len(university_counts) < 2:
    print("Недостаточно данных для определения второго университета по заявкам.")
else:
    # 2. Находим университет с вторым по числу заявок
    second_university = university_counts.index[1]

    # 3. Фильтруем данные для бакалавров в этом университете и находим минимальную начальную сумму кредита
    bachelors_data = data[(data['Университет'] == second_university) & 
                          (data['Тип_студента'].str.upper() == 'BACHELOR')]
    min_initial_credit = bachelors_data['Начальная_сумма'].min()
    
    # Проверка на NaN и вывод результата
    if pd.isna(min_initial_credit):
        print("Данные о начальной сумме кредита для бакалавров отсутствуют в данном университете.")
    else:
        print(int(min_initial_credit))
