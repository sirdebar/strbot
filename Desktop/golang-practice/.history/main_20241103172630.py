import pandas as pd

# Загрузка файла
file_path = 'credit-0b9d6b53-06a7-4321-91bc-d3635df3642c.xlsx'
data = pd.read_excel(file_path, header=1)

# Переименовываем столбцы (замените их на актуальные для вашего файла)
data.columns = ['Дата_заявки', 'Источник', 'Программа', 'Дата_начала', 'Начальная_сумма', 
                'Ставка', 'Срок', 'Кредитный_лимит', 'Годовой_доход', 'Месячный_доход',
                'Образование', 'Возраст', 'Паспорт', 'Пол', 'Город', 'Университет', 
                'Семья', 'Тип_студента', 'Курс', 'Средний_балл', 'Срок_окончания']

# Проверка уникальных значений в колонках для понимания структуры данных
print("Уникальные университеты:\n", data['Университет'].unique())
print("Уникальные типы студентов:\n", data['Тип_студента'].unique())

# Проверка, что в данных есть магистры и бакалавры
masters_data = data[data['Тип_студента'].str.upper() == 'MASTER']
print("\nЧисло заявок от магистров по университетам:\n", masters_data['Университет'].value_counts())

# Пробуем выбрать университет с вторым по числу заявок и ищем бакалавров
if len(masters_data['Университет'].value_counts()) < 2:
    print("\nНедостаточно данных для второго университета с заявками от магистров.")
else:
    second_university = masters_data['Университет'].value_counts().index[1]
    bachelors_data = data[(data['Университет'] == second_university) & 
                          (data['Тип_студента'].str.upper() == 'BACHELOR')]
    
    # Выводим информацию о найденных бакалаврах в данном университете
    print(f"\nДанные о бакалаврах в университете '{second_university}':")
    print(bachelors_data[['Начальная_сумма', 'Тип_студента', 'Университет']])
    
    # Проверяем минимальную начальную сумму кредита среди бакалавров
    min_initial_credit = bachelors_data['Начальная_сумма'].min()
    if pd.isna(min_initial_credit):
        print("\nДанные о начальной сумме кредита для бакалавров отсутствуют в данном университете.")
    else:
        print("\nМинимальная начальная сумма кредита для бакалавров:", int(min_initial_credit))
